# agents/explanation_agent.py

import os
from dotenv import load_dotenv

from langchain_groq import ChatGroq
from langchain_core.messages import HumanMessage

load_dotenv()

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    api_key=os.getenv("GROQ_API_KEY")
)


def explanation_agent(state):
    """
    Generate final NTRO Fire Intelligence Report.
    """

    prompt = f"""
You are an AI Disaster Intelligence Analyst for NTRO Sentinel.

Analyze this fire hotspot and produce a professional intelligence report.

## NASA FIRMS DATA
Latitude: {state['latitude']}
Longitude: {state['longitude']}
Brightness TI4: {state['bright_ti4']} K
Brightness TI5: {state['bright_ti5']} K
Fire Radiative Power: {state['frp']} MW
Detection Confidence: {state['confidence']}%

## WEATHER
Temperature: {state['temperature']}°C
Humidity: {state['humidity']}%
Wind Speed: {state['wind_speed']} km/h
Wind Direction: {state['wind_direction']}

## FIRE CLASSIFICATION
Fire Type: {state['fire_type']}
Fire Intensity: {state['fire_intensity']}
Heat Level: {state['heat_level']}

## SPREAD PREDICTION
Predicted Direction: {state['predicted_spread_direction']}
Confidence: {state['spread_confidence']}%

## DAMAGE ANALYSIS
Damage Score: {state['damage_score']}/100
Damage Category: {state['damage_category']}
Estimated Burn Area: {state['estimated_burn_area_km2']} km²
Estimated Burnout Time: {state['estimated_burnout_hours']} Hours

## RISK ANALYSIS
Risk Level: {state['risk_level']}
Critical Radius: {state['critical_radius_km']} km
Infrastructure Risk: {state['infrastructure_risk']}

## POPULATION IMPACT
Affected Buildings: {state['affected_buildings']}
Estimated Population: {state['affected_population']}
Evacuation Priority: {state['evacuation_priority']}

## REASONS GENERATED BY AGENTS
Spread Reason:
{state['spread_reason']}

Damage Reason:
{state['damage_reason']}

Risk Reason:
{state['risk_reason']}

Casualty Reason:
{state['casualty_reason']}

Generate a concise intelligence report with these sections:

### Fire Overview
### Why the Fire is Expected to Spread
### Damage Assessment
### Risk Assessment
### Estimated Population Impact
### Recommended Immediate Actions

Keep the report under 220 words.
"""

    response = llm.invoke([HumanMessage(content=prompt)])

    return {
        "explanation": response.content,
        "messages": [response],
        "llm_calls": state.get("llm_calls", 0) + 1
    }